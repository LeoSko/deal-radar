#!/usr/bin/env node
// Store one provider's credentials, from whatever `bin/capture.mjs <provider>`
// put on your clipboard. Run it again whenever a provider stops answering.
//
// Usage:
//   node import-tokens.mjs [wolt|bolt|foody] '<paste>'
//   node import-tokens.mjs foody -            # read the paste from stdin
//   node import-tokens.mjs '<paste>'          # provider defaults to wolt
//
// Get the paste with:
//   node bin/capture.mjs <provider>           # prints the console snippet

import { loadAuth, saveAuth, AUTH_PATH } from "../lib/auth.mjs";
import { configPath } from "../lib/config.mjs";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname } from "node:path";

async function readSource(arg) {
  if (!arg || arg === "-") {
    return new Promise((resolve, reject) => {
      let buf = "";
      process.stdin.setEncoding("utf8");
      process.stdin.on("data", (c) => (buf += c));
      process.stdin.on("end", () => resolve(buf));
      process.stdin.on("error", reject);
    });
  }
  if (existsSync(arg)) return readFile(arg, "utf8");
  return arg;
}

function jwtExpMs(token) {
  try {
    const [, b64] = token.split(".");
    const payload = JSON.parse(Buffer.from(b64, "base64").toString("utf8"));
    if (typeof payload.exp === "number") return payload.exp * 1000;
  } catch {}
  return null;
}

function parseInputs(src) {
  // Three accepted forms:
  //   1. {"wtoken": "<url-encoded JSON>", "wrtoken": "<url-encoded refresh>"}
  //   2. full `document.cookie` string (we'll regex out the two cookies)
  //   3. {"access_token": "...", "refresh_token": "..."} pre-extracted
  src = src.trim().replace(/^['"]|['"]$/g, "");
  if (src.startsWith("{")) {
    const obj = JSON.parse(src);
    if (obj.access_token && obj.refresh_token) return obj;
    if (obj.wtoken) {
      const wt = JSON.parse(decodeURIComponent(obj.wtoken));
      let rtok = obj.wrtoken ? decodeURIComponent(obj.wrtoken) : null;
      if (rtok && rtok.startsWith('"') && rtok.endsWith('"')) rtok = JSON.parse(rtok);
      return {
        access_token: wt.accessToken,
        access_token_expires_at: wt.expirationTime || jwtExpMs(wt.accessToken),
        refresh_token: rtok,
      };
    }
  }
  // assume raw document.cookie
  const wm = src.match(/__wtoken=([^;]+)/);
  const rm = src.match(/__wrtoken=([^;]+)/);
  if (!wm) throw new Error("Could not find __wtoken in input");
  const wt = JSON.parse(decodeURIComponent(wm[1]));
  let rtok = rm ? decodeURIComponent(rm[1]) : null;
  if (rtok && rtok.startsWith('"') && rtok.endsWith('"')) rtok = JSON.parse(rtok);
  return {
    access_token: wt.accessToken,
    access_token_expires_at: wt.expirationTime || jwtExpMs(wt.accessToken),
    refresh_token: rtok,
  };
}

// Bolt needs a long-lived refresh JWT plus the city slug its venue URLs are
// built from; deviceId/session_id are generated by the scanner on first run.
async function importBolt(src) {
  const path = configPath("bolt_auth.json");
  let fresh;
  try { fresh = JSON.parse(src.trim()); }
  catch { fresh = { refresh_token: src.trim() }; }        // tolerate a bare eyJ… token
  if (!/^eyJ/.test(fresh.refresh_token || "")) {
    throw new Error("No refresh token in the paste — expected an eyJ… JWT.");
  }
  const cityFlag = process.argv.find((a, i) => process.argv[i - 1] === "--city");
  const auth = existsSync(path) ? JSON.parse(await readFile(path, "utf8")) : {};
  auth.refresh_token = fresh.refresh_token;
  auth.city_slug = cityFlag || fresh.city_slug || auth.city_slug || null;
  delete auth.token;                                       // stale access token — re-minted on next run
  await writeFileSecure(path, auth);
  console.log(`Saved Bolt credentials to ${path}`);
  const exp = jwtExpMs(auth.refresh_token);
  if (exp) console.log(`refresh_token valid until ${new Date(exp).toISOString()}`);
  if (!auth.city_slug) {
    console.log("\nNo city_slug captured (were you on the food.bolt.eu home page?). Re-run from");
    console.log("a /en/<city>/… URL, or pass it yourself:");
    console.log("  node bin/import-tokens.mjs bolt '<paste>' --city <slug>");
  } else {
    console.log(`city_slug: ${auth.city_slug}`);
  }
}

// Foody has no token to refresh — the whole credential is the x-core-* header
// set of one logged-in session, so it needs re-capturing when it goes stale.
async function importFoody(src) {
  const path = configPath("foody_auth.json");
  const fresh = JSON.parse(src.trim());
  if (!fresh.headers || !fresh.base) {
    throw new Error("Expected the JSON the capture snippet copies (base + headers).");
  }
  const keys = Object.keys(fresh.headers).map((k) => k.toLowerCase());
  if (!keys.includes("x-core-session-id")) {
    throw new Error("Paste has no x-core-session-id — you were not logged in, or the captured\n" +
      "request was a guest one. Log in first, then re-run the snippet.");
  }
  await writeFileSecure(path, fresh);
  console.log(`Saved Foody session to ${path}`);
  if (!fresh.lat || !fresh.lng) {
    console.log("No coordinates in the capture — pass --lat/--lon, or use the report's address picker.");
  }
}

async function writeFileSecure(path, obj) {
  await mkdir(dirname(path), { recursive: true, mode: 0o700 });
  await writeFile(path, JSON.stringify(obj, null, 2) + "\n", { mode: 0o600 });
}

async function importWolt(src) {
  const fresh = parseInputs(src);
  if (!fresh.access_token || !fresh.refresh_token) {
    throw new Error("Need both access_token and refresh_token. Did you paste both __wtoken and __wrtoken?");
  }

  let auth;
  try {
    auth = await loadAuth();
  } catch {
    auth = {
      endpoints: {
        order_history: "https://consumer-api.wolt.com/order-tracking-api/v1/order_history/?limit={limit}",
        order_details: "https://consumer-api.wolt.com/order-tracking-api/v1/order_history/purchase/{order_id}?tips_use_percentage=true",
        me: "https://restaurant-api.wolt.com/v1/user/me",
        addresses: "https://restaurant-api.wolt.com/v2/delivery/info",
        promotions: "https://consumer-api.wolt.com/v1/pages/venue-list/promotions-near-you?lon={lon}&lat={lat}",
        venue_static: "https://consumer-api.wolt.com/order-xp/web/v1/pages/venue/slug/{venue_id_or_slug}/static",
        venue_dynamic: "https://consumer-api.wolt.com/order-xp/web/v1/venue/slug/{venue_slug}/dynamic/?lat={lat}&lon={lon}&selected_delivery_method=homedelivery",
        assortment: "https://consumer-api.wolt.com/consumer-api/consumer-assortment/v1/venues/slug/{venue_slug}/assortment",
        refresh: "https://authentication.wolt.com/v1/wauth2/access_token",
      },
      work_address: null,
    };
  }
  auth.access_token = fresh.access_token;
  auth.access_token_expires_at = fresh.access_token_expires_at || jwtExpMs(fresh.access_token);
  auth.refresh_token = fresh.refresh_token;
  await saveAuth(auth);

  const expSec = Math.round((auth.access_token_expires_at - Date.now()) / 1000);
  console.log(`Saved tokens to ${AUTH_PATH}`);
  console.log(`access_token expires in ${expSec}s (${new Date(auth.access_token_expires_at).toISOString()})`);
  console.log(`refresh_token length: ${auth.refresh_token.length}`);
  if (!auth.work_address) {
    console.log("\nNo work_address saved yet. Run:");
    console.log("  node bin/set-address.mjs");
  }
}

const IMPORTERS = { wolt: importWolt, bolt: importBolt, foody: importFoody };

async function main() {
  const args = process.argv.slice(2);
  // `import-tokens.mjs <provider> <paste>`, or the older provider-less form.
  const provider = IMPORTERS[args[0]] ? args.shift() : "wolt";
  const arg = args[0];
  if (!arg) {
    console.error("Usage: import-tokens.mjs [wolt|bolt|foody] '<paste>' | <file> | -");
    console.error("Get the paste with: node bin/capture.mjs <provider>");
    process.exit(2);
  }
  await IMPORTERS[provider](await readSource(arg));
}

main().catch((e) => {
  console.error(e.message || e);
  process.exit(1);
});
